#!/bin/bash
# =============================================================================
# 脚本名称：03_file_permission_check.sh
# 功能描述：检查文件权限（可读、可写、可执行）
# 难度等级：⭐⭐⭐ 中级
# 知识点：
#   - if 条件判断
#   - 文件权限测试：-r, -w, -x
#   - && 逻辑与（前命令成功则执行后命令）
#   - || 逻辑或（前命令失败则执行后命令）
#   - sh $0 重新执行本脚本
#   - exit 1 退出并返回状态码
# 使用方法：
#   chmod +x 03_file_permission_check.sh
#   ./03_file_permission_check.sh
# 文件权限测试：
#   -r 文件 - 当前用户是否可读 (read)
#   -w 文件 - 当前用户是否可写 (write)
#   -x 文件 - 当前用户是否可执行 (execute)
# =============================================================================

# 提示用户输入文件名
read -p "input a file:" file

# 检查文件是否存在
if [ ! -e $file ]; then
	echo "$file is not exist"
	# exit 1		# 直接退出 shell	
	sh $0		# 再次执行本脚本，相当于是产生一个子进程	
	exit 1		# 这里的退出是退出父进程
fi

# 检查文件权限
# && 表示"与"：如果前面的测试成功，则执行后面的 echo
# || 表示"或"：如果前面的测试失败，则执行后面的 echo
[ -r $file ] && echo "当前用户对其可读" || echo "当前用户对其不可读"
[ -w $file ] && echo "当前用户对其可写" || echo "当前用户对其不可写"
[ -x $file ] && echo "当前用户对其执行" || echo "当前用户对其不可执行"

# 说明：
# 1. [ -r $file ] 测试当前用户是否对文件有读权限
# 2. && 是短路运算符：如果左边为真，才执行右边
# 3. || 也是短路运算符：如果左边为假，才执行右边
# 4. sh $0 会启动一个新的子进程执行本脚本
# 5. exit 1 退出当前进程（父进程），子进程继续运行
# 6. 权限是相对于当前用户而言的，不同用户可能有不同权限
