#!/bin/bash
# =============================================================================
# 脚本名称：02_menu_system.sh
# 功能描述：多级菜单系统 - 主菜单和子菜单
# 难度等级：⭐⭐⭐ 中级
# 知识点：
#   - echo 格式化输出
#   - case 语句处理菜单选项
#   - clear 清屏
#   - read -p 读取用户选择
#   - exit 0 正常退出
# 使用方法：
#   chmod +x 02_menu_system.sh
#   ./02_menu_system.sh
# =============================================================================

# 显示主菜单
echo "**************************"
echo "*	  欢迎，这是总菜单     *"
echo "**************************"
echo "		操作类型	"
echo "		1-系统		"
echo "		2-程序		"
echo "		3-数据库	"
echo "		0-退出		"
echo "**************************"

# 读取用户选择
read -p "请选择你要操作的类型:" choice

# 显示空行
echo

# 处理用户选择
case "$choice" in 
	0 )
		# 选择 0，退出程序
		echo "谢谢使用，如有 bug，请邮件给 xxxx@126.com"
		exit 0
		;;
	1 )
		# 选择 1，进入系统子菜单
		clear  # 清屏
		
		# 显示系统子菜单
		echo "**************************"
		echo "     欢迎来到系统子菜单   "
		echo "**************************"
		echo "          操作类型        "
		echo "          1-备份          "
		echo "          2-维护          "
		echo "          3-优化          "
		echo "          0-退出          "
		echo "**************************"
		;;
	* )
		# 其他选择，显示默认提示
		echo "......."
esac

# 说明：
# 1. case 语句适合处理菜单选择
# 2. 每个选项以 ) 结尾，以 ;; 结束
# 3. * 是默认选项（匹配所有未列出的情况）
# 4. clear 清屏让界面更干净
# 5. exit 0 表示正常退出（0 是成功状态码）

