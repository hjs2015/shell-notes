#!/bin/bash
# =============================================================================
# 脚本名称：11_generate_phone_all.sh
# 功能描述：生成所有号段的手机号码
# 难度等级：⭐⭐⭐ 中级
# 知识点：
#   - 数组定义和访问
#   - ${array[$index]} 数组元素访问
#   - $RANDOM%14 随机索引
#   - for 循环
#   - >> 追加到文件
# 使用方法：
#   chmod +x 11_generate_phone_all.sh
#   ./11_generate_phone_all.sh
# 功能说明：
#   生成 1000 个随机手机号码，支持多个号段
#   号段包括：130-139, 155, 158, 186, 189
# =============================================================================

# 定义手机号段数组
# 包含中国移动、联通、电信的常见号段
array=(130 131 132 133 134 135 136 137 138 139 155 158 186 189)

# 循环 1000 次，生成 1000 个手机号
for i in `seq 1000`
do
	# 随机选择一个号段（0-13 的随机索引）
	ran1=$[$RANDOM%14]
	
	# 获取号段前缀（如 130, 135, 189 等）
	head=${array[$ran1]}
	
	# 生成 8 位随机数字
	n1=$[$RANDOM%10]
	n2=$[$RANDOM%10]
	n3=$[$RANDOM%10]
	n4=$[$RANDOM%10]
	n5=$[$RANDOM%10]
	n6=$[$RANDOM%10]
	n7=$[$RANDOM%10]
	n8=$[$RANDOM%10]
	
	# 拼接成完整手机号并追加到文件
	echo "$head$n1$n2$n3$n4$n5$n6$n7$n8" >> phonenum.txt
done

# 说明：
# 1. array=(...) 定义数组
# 2. ${array[$ran1]} 访问数组元素
# 3. $RANDOM%14 生成 0-13 的随机数（数组索引）
# 4. 号段说明：
#    - 130-139: 中国联通
#    - 155, 158: 中国联通
#    - 186: 中国联通
#    - 189: 中国电信
# 5. 生成的号码是随机的，不是真实用户

