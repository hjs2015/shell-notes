#!/bin/bash
# ============================================================================
# 脚本名称：28_exit_codes.sh
# 功能描述：退出码详解 - 理解和使用退出码
# 难度等级：⭐⭐⭐ 进阶级
# 知识点：退出码、$?、自定义退出码、常见退出码
# ============================================================================

# 颜色定义
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

echo "============================================================================"
echo "  退出码详解"
echo "============================================================================"
echo ""

# 1. 检查上一个命令的退出码
echo -e "${YELLOW}[1] 检查上一个命令的退出码${NC}"
ls /etc/passwd
echo "退出码：$?"

echo ""

# 2. 成功命令的退出码
echo -e "${YELLOW}[2] 成功命令的退出码${NC}"
echo "成功执行"
echo "退出码：$?"

echo ""

# 3. 失败命令的退出码
echo -e "${YELLOW}[3] 失败命令的退出码${NC}"
ls /nonexistent_file 2>/dev/null
echo "退出码：$?"

echo ""

# 4. 自定义退出码
echo -e "${YELLOW}[4] 自定义退出码${NC}"
exit_with_code() {
    local code=$1
    echo "脚本将以退出码 $code 结束"
    exit $code
}

# 5. 常见退出码含义
echo -e "${YELLOW}[5] 常见退出码含义${NC}"
echo "  0  - 成功"
echo "  1  - 一般错误"
echo "  2  - 误用 shell 命令"
echo "  126 - 命令不可执行"
echo "  127 - 命令未找到"
echo "  128+ - 信号退出（128+信号值）"

echo ""
echo -e "${GREEN}[✓] 退出码演示完成${NC}"
exit 0
