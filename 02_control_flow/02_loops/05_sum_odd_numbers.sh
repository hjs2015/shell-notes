#!/bin/bash
# =============================================================================
# 脚本名称：05_sum_odd_numbers.sh
# 功能描述：计算 1-100 的奇数和（三种方法）
# 难度等级：⭐⭐ 入门
# 知识点：
#   - for 循环
#   - seq 命令生成序列
#   - $[表达式] 算术运算
#   - % 取模运算（求余数）
#   - && 逻辑与
#   - continue 跳过本次循环
# 使用方法：
#   chmod +x 05_sum_odd_numbers.sh
#   ./05_sum_odd_numbers.sh
# =============================================================================

# 方法 1：使用 seq 1 2 100 生成奇数序列
# seq 1 2 100 生成：1 3 5 7 ... 99（从 1 开始，步长为 2，到 100 结束）
sum=0
for i in `seq 1 2 100`
do
	sum=$[$sum+$i]  # $[] 是算术运算，等价于 $(())
done
echo $sum  # 输出：2500

# 方法 2：遍历 1-100，判断是否为奇数
sum=0
for i in `seq 100`
do
	# $[$i%2] 计算 i 除以 2 的余数
	# -eq 1 表示等于 1（奇数）
	# && 表示如果前面为真，则执行后面的命令
	[ $[$i%2] -eq 1 ]  && sum=$[$sum+$i]
done
echo $sum  # 输出：2500

# 方法 3：使用 continue 跳过偶数
sum=0
for i in `seq 100`
do
	# 如果是偶数（能被 2 整除），跳过本次循环
	[ $[$i%2] -eq 0 ] && continue
	sum=$[$sum+$i]
done
echo $sum  # 输出：2500

# 说明：
# 1. seq 1 2 100 生成从 1 到 100 的奇数序列（步长为 2）
# 2. $[表达式] 和 $(()) 都可以进行算术运算
# 3. % 是取模运算符，返回除法的余数
# 4. 奇数 % 2 = 1，偶数 % 2 = 0
# 5. && 是短路运算符：如果左边为真，才执行右边
# 6. continue 跳过本次循环剩余语句，继续下一次循环
