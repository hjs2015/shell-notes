#!/bin/bash
# =============================================================================
# 脚本名称：07_rdate_monitor.sh
# 功能描述：时间同步监控 - 监控时间同步服务状态
# 难度等级：⭐⭐⭐⭐ 高级
# 知识点：
#   - while true 无限循环
#   - rdate -s 从时间服务器同步时间
#   - $? 检查上一个命令的退出状态
#   - mail 发送邮件通知
#   - count+=1 计数器累加
#   - sleep 30 暂停 30 秒
# 使用方法：
#   chmod +x 07_rdate_monitor.sh
#   sudo ./07_rdate_monitor.sh
# 应用场景：
#   监控系统时间同步状态，确保时间准确
#   用于对时间敏感的服务器（如数据库、日志服务器）
# =============================================================================

# 无限循环监控
while true
do
	# 初始化计数器
	count=0
	
	# 尝试从时间服务器同步时间
	# rdate -s 192.168.2.9 从指定服务器同步时间
	# &> /dev/null 不显示输出
	rdate -s 192.168.2.9 &> /dev/null
	
	# 检查同步是否成功
	# $? 是上一个命令的退出状态码
	# -ne 0 表示不等于 0（失败）
	if [ $? -ne 0 ]; then
		# 同步失败，发送邮件通知
		echo "failed" | mail -s "rdate mail" root
		# count=0  # 如果要求连续 100 次成功才发送成功信息，那么失败一次我们也计数器清 0
	else
		# 同步成功，计数器加 1
		count+=1
		
		# 如果连续成功 100 次，发送成功通知
		if [ $count -eq 100 ]; then
			echo "success" | mail -s "rdate mail" root
			count=0  # 重置计数器
		fi
	fi
	
	# 暂停 30 秒
	sleep 30
done

# 说明：
# 1. rdate 是远程日期协议客户端，用于从时间服务器同步时间
# 2. -s 选项表示设置系统时间（set）
# 3. $? 是特殊变量，保存上一个命令的退出状态码
# 4. count+=1 是 Bash 的算术运算，等价于 count=$((count+1))
# 5. 这个脚本应该作为后台服务运行

# 注意：
# 1. 需要 root 权限才能设置系统时间
# 2. 需要配置邮件服务才能发送邮件
# 3. 实际生产中应该使用 ntpd 或 chrony 服务
# 4. 192.168.2.9 应该替换为实际的时间服务器地址

# 扩展：
# 可以配合 cron 或 systemd 运行，确保时间同步服务正常
