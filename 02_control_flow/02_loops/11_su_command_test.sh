#!/bin/bash
# =============================================================================
# 脚本名称：11_su_command_test.sh
# 功能描述：su 命令测试 - 切换用户执行命令
# 难度等级：⭐⭐ 入门
# 知识点：
#   - su - user1 切换用户
#   - -c "command" 执行单个命令
#   - <<EOF ... EOF heredoc 多行输入
# 使用方法：
#   chmod +x 11_su_command_test.sh
#   sudo ./11_su_command_test.sh
# 注意：需要系统中有 user1 用户
# =============================================================================

# 方法 1（注释掉）：使用 heredoc 多行输入
#su - user1 <<EOF
#touch haha
#EOF

# 方法 2：使用 -c 参数执行单个命令
# su - user1 切换到 user1 用户（- 表示加载用户的环境变量）
# -c "touch hehe" 执行 touch hehe 命令
su - user1 -c "touch hehe"

# 说明：
# 1. su 是"switch user"的缩写，用于切换用户
# 2. su - user1 切换到 user1 用户并加载其环境变量
# 3. su user1 切换但不加载环境变量（不推荐）
# 4. -c "command" 只执行一个命令就返回
# 5. <<EOF ... EOF 是 heredoc，用于多行输入

# 实际应用场景：
# 1. 以其他用户身份执行特定命令
# 2. 在脚本中临时切换权限
# 3. 测试其他用户的环境

# 注意：
# 1. 需要目标用户存在（如 user1）
# 2. 可能需要 root 权限才能切换用户
# 3. 执行的文件权限要正确
