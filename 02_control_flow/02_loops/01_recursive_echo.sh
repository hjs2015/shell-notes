#!/bin/bash
# =============================================================================
# 脚本名称：01_recursive_echo.sh
# 功能描述：递归执行脚本 - 演示递归调用
# 难度等级：⭐⭐ 入门
# 知识点：
#   - echo 输出
#   - sleep 1 暂停 1 秒
#   - sh $0 递归调用自身
#   - exit 1 退出
# 使用方法：
#   chmod +x 01_recursive_echo.sh
#   ./01_recursive_echo.sh
# 注意：
#   这个脚本会无限递归执行，需要用 Ctrl+C 中断
# =============================================================================

# 输出一串 1
echo "1111111111"

# 暂停 1 秒
sleep 1

# 递归调用自身
# sh $0 表示用 sh 解释器执行当前脚本
# $0 表示脚本本身的名称
sh $0

# 退出（这行实际上不会执行，因为上面已经递归了）
exit 1

# 说明：
# 1. 这是一个递归脚本的例子
# 2. 每次执行都会输出"1111111111"，然后暂停 1 秒，再执行自己
# 3. 这会产生无限递归，直到用 Ctrl+C 中断
# 4. 实际应用中很少这样用，因为会创建无数个子进程
# 5. 更好的递归方式应该有终止条件

# 警告：
# 不要在生产环境中这样使用，会导致系统资源耗尽！
