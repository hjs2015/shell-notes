#!/bin/bash
# =============================================================================
# 脚本名称：10_find_dead_links.sh
# 功能描述：查找目录中的死链接
# 难度等级：⭐⭐⭐ 中级
# 知识点：
#   - read -p 读取用户输入
#   - [ -d $dir ] 判断是否为目录
#   - find $dir -type l 查找符号链接
#   - [ ! -e $i ] 判断链接目标是否存在
#   - sh $0 重新执行脚本
# 使用方法：
#   chmod +x 10_find_dead_links.sh
#   ./10_find_dead_links.sh
# 什么是死链接？
#   符号链接（软链接）指向的目标文件不存在时，称为死链接
#   例如：ln -s /nonexistent/file link
# =============================================================================

# 提示用户输入目录
read -p "输入一个目录:" dir

# 检查是否为目录或目录是否存在
# ! -d 表示"不是目录"
if [ ! -d $dir ]; then
	echo "不是目录或不存在，重新输入"
	sh $0  # 重新执行本脚本
	exit 1  # 退出当前进程
fi

# 遍历目录中的所有符号链接
# find $dir -type l 查找类型为 link 的文件（符号链接）
for i in `find $dir -type l`
do
	# 检查链接目标是否存在
	# ! -e 表示"不存在"
	# && 表示如果前面为真，则执行后面
	[ ! -e $i ] && echo "$i是死链接"
done 

# 说明：
# 1. find -type l 只查找符号链接，不查找普通文件
# 2. -e 测试文件或链接目标是否存在
# 3. 对于符号链接，-e 测试的是链接目标，不是链接本身
# 4. 如果要测试链接本身是否存在，用 -L
# 5. sh $0 会创建一个新的子进程执行脚本

