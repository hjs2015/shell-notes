#!/bin/bash
# =============================================================================
# 脚本名称：08_guess_number_game.sh
# 功能描述：猜数字游戏（1-100）
# 难度等级：⭐⭐⭐ 中级
# 知识点：
#   - $RANDOM 生成随机数
#   - % 取模运算
#   - while true 无限循环
#   - if-elif-else 多分支判断
#   - -gt 大于，-lt 小于
#   - break 退出循环
# 使用方法：
#   chmod +x 08_guess_number_game.sh
#   ./08_guess_number_game.sh
# 游戏规则：
#   计算机会随机生成一个 1-100 的整数
#   玩家不断猜数字，计算机会提示"大了"或"小了"
#   猜对后游戏结束
# =============================================================================

# 显示游戏说明
echo "猜一个 1-100 的整数，猜对砸蛋:" 

# 生成随机数
# $RANDOM 生成 0-32767 的随机整数
# % 100 取模，得到 0-99
# +1 加 1，得到 1-100
num=$[$RANDOM%100+1]

# 无限循环，直到猜对为止
while true
do
	# 读取用户猜测
	read -p "请猜:" gnum
	
	# 判断猜测结果
	if [ $gnum -gt $num ]; then
		echo "大了"  # 猜测的数字太大
	elif [ $gnum -lt $num ]; then
		echo "小了"  # 猜测的数字太小
	else	
		echo "对了"  # 猜对了！
		break  # 退出循环
	fi
done

# 游戏结束
echo "砸蛋"

# 说明：
# 1. $RANDOM 是 Bash 的内置变量，每次使用都会生成不同的随机数
# 2. % 是取模运算，例如：123 % 100 = 23
# 3. while true 创建无限循环，必须用 break 退出
# 4. -gt 表示"大于" (greater than)
# 5. -lt 表示"小于" (less than)
# 6. break 立即退出当前循环

