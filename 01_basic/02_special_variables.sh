#!/bin/bash
# =============================================================================
# 脚本名称：02_special_variables.sh
# 功能描述：演示 Shell 中的特殊变量
# 难度等级：⭐⭐ 入门
# 知识点：
#   - $0  - 脚本名称
#   - $1, $2, $3 - 位置参数（第 1、2、3 个参数）
#   - $$  - 当前脚本的进程 ID (PID)
#   - $#  - 传递给脚本的参数个数
#   - $*  - 所有位置参数（作为一个单词）
#   - $@  - 所有位置参数（作为单独的单词）
# 使用方法：
#   chmod +x 02_special_variables.sh
#   ./02_special_variables.sh arg1 arg2 arg3
# =============================================================================

# 显示脚本名称 ($0)
echo '$0 is: ' "$0"

# 显示第 1 个参数 ($1)
echo '$1 is: ' "$1"

# 显示第 2 个参数 ($2)
echo '$2 is: ' "$2"

# 显示第 3 个参数 ($3)
echo '$3 is: ' "$3"

# 显示当前脚本的进程 ID ($$)
echo '$$ is: ' "$$"

# 显示传递给脚本的参数个数 ($#)
echo '$# is: ' "$#"

# 显示所有位置参数 ($*)
echo '$* is: ' "$*"

# 显示所有位置参数 ($@)
echo '$@ is: ' "$@"

# 示例输出（运行 ./02_special_variables.sh a b c）:
# $0 is:  ./02_special_variables.sh
# $1 is:  a
# $2 is:  b
# $3 is:  c
# $$ is:  12345
# $# is:  3
# $* is:  a b c
# $@ is:  a b c
