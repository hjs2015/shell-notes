#!/bin/bash
# =============================================================================
# 脚本名称：03_countdown_2018.sh
# 功能描述：倒计时到 2018 年元旦
# 难度等级：⭐⭐⭐ 中级
# 知识点：
#   - date +%s 获取时间戳（秒）
#   - date -d "20180101" 指定日期
#   - while true 无限循环
#   - 时间计算（天、时、分、秒）
#   - clear 清屏
#   - sleep 1 暂停 1 秒
# 使用方法：
#   chmod +x 03_countdown_2018.sh
#   ./03_countdown_2018.sh
# =============================================================================

# 计算 2018 年 1 月 1 日的时间戳（秒）
# date +%s 返回从 1970-01-01 00:00:00 UTC 到现在的秒数
goal=`date +%s -d 20180101`

# 无限循环，直到时间到达 2018 年元旦
while true
do
	# 获取当前时间戳
	now=`date +%s`
	
	# 如果目标时间减去当前时间等于 0，说明已经到了
	if [ $[$goal-$now] -eq 0 ]; then
		break  # 退出循环
	fi
	
	# 计算剩余时间
	# 86400 = 24 * 60 * 60（一天的秒数）
	# 3600 = 60 * 60（一小时的秒数）
	# 60（一分钟的秒数）
	day=$[($goal-$now)/86400]      # 剩余天数
	hour=$[($goal-$now)%86400/3600]  # 剩余小时数
	minute=$[($goal-$now)%3600/60]   # 剩余分钟数
	second=$[($goal-$now)%60]        # 剩余秒数
	
	# 清屏
	clear
	
	# 显示倒计时
	echo "离 2018 年还有$day天:$hour时:$minute分:$second秒"
	
	# 暂停 1 秒
	sleep 1
done

# 时间到了，显示祝福
echo "2018 年元旦快乐!!!"

# 说明：
# 1. 时间戳是从 1970-01-01 00:00:00 UTC 开始到现在的秒数
# 2. 通过时间戳相减可以得到两个时间之间的秒数差
# 3. 用除法和取模运算将秒数转换为天、时、分、秒
# 4. clear 清屏让显示更美观
# 5. sleep 1 让倒计时每秒更新一次

