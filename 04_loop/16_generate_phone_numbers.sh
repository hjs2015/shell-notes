#!/bin/bash
# =============================================================================
# 脚本名称：16_generate_phone_numbers.sh
# 功能描述：生成随机手机号码
# 难度等级：⭐⭐⭐ 中级
# 知识点：
#   - $RANDOM 生成随机数
#   - %10 取模运算（0-9）
#   - >> 追加到文件
#   - for 循环
#   - 变量拼接
# 使用方法：
#   chmod +x 16_generate_phone_numbers.sh
#   ./16_generate_phone_numbers.sh
# 功能说明：
#   生成 1000 个随机手机号码，保存到 phonenum.txt
#   号码格式：139 + 8 位随机数字
# =============================================================================

# 删除旧文件（如果存在）
rm phonenum.txt -rf

# 循环 1000 次，生成 1000 个手机号
for i in `seq 1000`
do
	# 生成 8 位随机数字（每位 0-9）
	n1=$[$RANDOM%10]
	n2=$[$RANDOM%10]
	n3=$[$RANDOM%10]
	n4=$[$RANDOM%10]
	n5=$[$RANDOM%10]
	n6=$[$RANDOM%10]
	n7=$[$RANDOM%10]
	n8=$[$RANDOM%10]
	
	# 拼接成手机号码：139 + 8 位随机数
	# >> 追加到文件（不覆盖）
	echo "139$n1$n2$n3$n4$n5$n6$n7$n8" >> phonenum.txt
done

# 说明：
# 1. $RANDOM 是 Bash 内置变量，生成 0-32767 的随机数
# 2. %10 取模运算，得到 0-9 的个位数
# 3. 139 是中国移动的经典号段
# 4. >> 是追加，> 是覆盖
# 5. 生成的号码可能重复，不是真实的手机号

# 注释掉的另一种方法：
# 使用数学运算生成 8 位数，然后检查位数
# 这种方法更复杂，但可以减少重复

# 注意：
# 1. 这些是随机生成的号码，不是真实用户
# 2. 仅用于测试和练习
# 3. 不要用于骚扰或非法用途

