GREEN='\033[0;32m'; NC='\033[0m'
print_color() { echo -e "${!1}${2}${NC}"; }
print_separator() { echo "========================================"; }
print_separator; print_color CYAN "并发执行演示"; print_separator
echo "启动 3 个后台任务..."
for i in 1 2 3; do
  (echo "任务 $i 开始"; sleep 1; echo "任务 $i 完成") &
done
wait
echo "所有任务完成"
print_color GREEN "演示完成！"
