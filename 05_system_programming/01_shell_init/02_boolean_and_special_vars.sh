#!/bin/bash
# =============================================================================
# 脚本：02_boolean_and_special_vars.sh
# 功能：演示布尔值和特殊变量
# 难度：⭐⭐
# 知识点：
#   - true/false 命令
#   - 特殊变量 ($0, $*, $@, $#, $$, $!, $?)
# 使用方法：
#   ./02_boolean_and_special_vars.sh [参数 1] [参数 2] ...
# =============================================================================

echo "=========================================="
echo "【1】布尔值"
echo "=========================================="

echo "假值 (false)："
false
echo "返回值：$? (1 表示假)"

echo ""
echo "真值 (true)："
true
echo "返回值：$? (0 表示真)"

echo ""
echo "=========================================="
echo "【2】特殊变量演示"
echo "=========================================="

echo "传入参数个数 ($#): $#"
echo "所有参数 ($*): $*"
echo "所有参数 ($@): $@"
echo "脚本名称 ($0): $0"
echo "当前进程 PID ($$): $$"
echo "上一个后台进程 PID ($!): $!"
echo "上一个命令返回值 ($?): $?"

echo ""
echo "=========================================="
echo "【3】$* vs $@ 的区别"
echo "=========================================="

echo "遍历 \$* (作为整体)："
for arg in "$*"; do
    echo "  参数：[$arg]"
done

echo ""
echo "遍历 \$@ (独立元素)："
for arg in "$@"; do
    echo "  参数：[$arg]"
done

echo ""
echo "=========================================="
echo "【4】实战示例"
echo "=========================================="

# 示例 1：检查参数数量
if [ $# -eq 0 ]; then
    echo "⚠️  没有传入参数"
    echo "💡 用法：$0 参数 1 参数 2 ..."
elif [ $# -eq 1 ]; then
    echo "✅ 传入 1 个参数：$1"
else
    echo "✅ 传入 $# 个参数"
    echo "   第 1 个：$1"
    echo "   第 2 个：$2"
    echo "   其他：${@:3}"
fi

# 示例 2：后台进程
echo ""
echo "示例：启动后台进程"
sleep 5 &
bg_pid=$!
echo "后台进程 PID: $bg_pid"
echo "可以使用 kill $bg_pid 终止它"

echo ""
echo "=========================================="
echo "学习完成！"
echo "=========================================="
