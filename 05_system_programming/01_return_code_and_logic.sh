#!/bin/bash
# =============================================================================
# 脚本：01_return_code_and_logic.sh
# 功能：演示命令返回状态码和逻辑运算符
# 难度：⭐⭐
# 知识点：
#   - 命令返回值 ($?)
#   - 逻辑与 (&&)
#   - 逻辑或 (||)
#   - 分号 (;)
# 使用方法：
#   ./01_return_code_and_logic.sh
# =============================================================================

echo "=========================================="
echo "【1】命令返回状态码"
echo "=========================================="

# 成功命令
echo "执行成功命令：date"
date
echo "返回值：$?"
echo ""

# 失败命令
echo "执行失败命令：date111 (不存在的命令)"
date111 2>/dev/null
echo "返回值：$?"
echo ""

echo "=========================================="
echo "【2】逻辑与 (&&) - 前成功才执行后"
echo "=========================================="

echo "示例 1：前面成功，后面执行"
echo "命令：date && echo '执行成功'"
date && echo '✅ 执行成功'
echo ""

echo "示例 2：前面失败，后面不执行"
echo "命令：date111 && echo '执行成功'"
date111 2>/dev/null && echo '✅ 执行成功'
echo "(后面命令未执行)"
echo ""

echo "=========================================="
echo "【3】逻辑或 (||) - 前失败才执行后"
echo "=========================================="

echo "示例 1：前面成功，后面不执行"
echo "命令：date || echo '执行失败'"
date || echo '❌ 执行失败'
echo ""

echo "示例 2：前面失败，后面执行"
echo "命令：date111 || echo '执行失败'"
date111 2>/dev/null || echo '❌ 执行失败'
echo ""

echo "=========================================="
echo "【4】分号 (;) - 无论成败都执行"
echo "=========================================="

echo "示例 1：前面成功"
echo "命令：date ; echo '不管成败都执行'"
date ; echo '✅ 不管成败都执行'
echo ""

echo "示例 2：前面失败"
echo "命令：date111 ; echo '不管成败都执行'"
date111 2>/dev/null ; echo '✅ 不管成败都执行'
echo ""

echo "=========================================="
echo "【5】实战技巧"
echo "=========================================="

# 技巧 1：检查命令是否成功
echo "技巧 1：检查命令执行结果"
mkdir -p /tmp/test_dir && echo "✅ 目录创建成功" || echo "❌ 目录创建失败"

# 技巧 2：链式检查
echo ""
echo "技巧 2：链式检查（全部成功才继续）"
[ -d /tmp ] && [ -w /tmp ] && echo "✅ /tmp 目录存在且可写" || echo "❌ /tmp 目录有问题"

# 技巧 3：错误处理
echo ""
echo "技巧 3：错误处理模式"
command_not_exist 2>/dev/null || {
    echo "⚠️  命令执行失败"
    echo "💡 建议：检查命令是否存在"
}

echo ""
echo "=========================================="
echo "学习完成！"
echo "=========================================="
