GREEN='\033[0;32m'; NC='\033[0m'
print_color() { echo -e "${!1}${2}${NC}"; }
print_separator() { echo "========================================"; }
print_separator; print_color CYAN "作业控制演示"; print_separator
echo "启动后台任务..."
sleep 5 &
echo "作业列表："
jobs -l
echo "后台任务 PID：$!"
print_color GREEN "演示完成！"
