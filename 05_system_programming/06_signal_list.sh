GREEN='\033[0;32m'; NC='\033[0m'
print_color() { echo -e "${!1}${2}${NC}"; }
cleanup() { echo "捕获到退出信号，清理中..."; exit 0; }
trap cleanup SIGINT SIGTERM
print_color CYAN "信号处理演示"
echo "按 Ctrl+C 测试信号捕获"
echo "PID: $$"
echo "按 Ctrl+C 退出..."
sleep 3
print_color GREEN "演示完成！"
