GREEN='\033[0;32m'; NC='\033[0m'
print_color() { echo -e "${!1}${2}${NC}"; }
print_separator() { echo "========================================"; }
print_separator; print_color CYAN "数组操作演示"; print_separator
arr=(1 2 3 4 5)
echo "原数组：${arr[*]}"
echo "切片：${arr[@]:1:3}"
echo "长度：${#arr[@]}"
print_color GREEN "演示完成！"
