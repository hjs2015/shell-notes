GREEN='\033[0;32m'; NC='\033[0m'
print_color() { echo -e "${!1}${2}${NC}"; }
str="Hello World"
echo "原字符串：$str"
echo "长度：${#str}"
echo "截取：${str:0:5}"
echo "替换：${str/World/Shell}"
echo "大写：${str^^}"
echo "小写：${str,,}"
print_color GREEN "演示完成！"
