GREEN='\033[0;32m'; NC='\033[0m'
print_color() { echo -e "${!1}${2}${NC}"; }
declare -A dict=([name]="Alice" [age]=25 [city]="Shenzhen")
echo "关联数组演示"
echo "姓名：${dict[name]}"
echo "年龄：${dict[age]}"
echo "城市：${dict[city]}"
echo "所有键：${!dict[*]}"
echo "所有值：${dict[*]}"
print_color GREEN "演示完成！"
