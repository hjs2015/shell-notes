#!/bin/bash
# =============================================================================
# 脚本名称：04_ping_check.sh
# 功能描述：检查 IP 地址的连通性
# 难度等级：⭐⭐ 入门
# 知识点：
#   - read -p 读取用户输入
#   - ping -c 1 - 发送 1 个 ICMP 包
#   - &> /dev/null - 重定向所有输出到空设备（不显示）
#   - $? - 上一个命令的退出状态码（0 表示成功）
#   - if [ $? -ne 0 ] - 如果不等于 0（失败）
# 使用方法：
#   chmod +x 04_ping_check.sh
#   ./04_ping_check.sh
# =============================================================================

# 提示用户输入 IP 地址
read -p "input a ip:" ip

# ping 测试，发送 1 个包
# &> /dev/null 表示将所有输出（标准输出和错误输出）重定向到空设备
ping -c 1 $ip &> /dev/null

# 检查 ping 命令的退出状态码
# $? 是上一个命令的返回值，0 表示成功，非 0 表示失败
# -ne 表示"不等于" (not equal)
if [ $? -ne 0 ]; then
	echo "$ip is not ok"
else
	echo "$ip is ok"
fi

# 说明：
# 1. ping 命令用于测试网络连通性
# 2. -c 1 表示只发送 1 个数据包
# 3. 如果目标主机可达，ping 返回 0；否则返回非 0
# 4. 可以批量测试多个 IP：for ip in 192.168.1.{1..10}; do ping -c 1 $ip; done
