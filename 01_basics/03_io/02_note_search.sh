#!/bin/bash
# =============================================================================
# 脚本名称：02_note_search.sh
# 功能描述：笔记查找工具 - 根据关键字查找笔记文件
# 难度等级：⭐⭐⭐ 中级
# 知识点：
#   - read -p 读取用户输入
#   - cd 切换目录
#   - grep 搜索关键字
#   - cut -d":" -f1 按冒号分割取第 1 列
#   - sort 排序
#   - uniq -c 去重并计数
#   - tail -1 取最后一行
#   - awk '{print $2}' 取第 2 列
#   - gedit 打开文件
# 使用方法：
#   chmod +x 02_note_search.sh
#   ./02_note_search.sh
# 注意：
#   需要修改路径 /share/20170331/ 为实际的笔记目录
# =============================================================================

# 提示用户输入笔记分类
read -p "输入你要查找笔记的分类 (basic|shell|mysql|program|arch|oracle):" dir

# 切换到笔记目录
cd /share/20170331/$dir

# 提示用户输入查找的关键字
read -p "输入你要查找笔记的关键字:" keyword

# 查找包含关键字的文件并打开
# 管道说明：
# 1. grep $keyword * - 搜索当前目录下包含关键字的文件
# 2. cut -d":" -f1 - 按冒号分割，取文件名（第 1 列）
# 3. sort - 排序
# 4. grep -v ~$ - 排除临时文件（以~结尾）
# 5. uniq -c - 去重并统计每个文件出现的次数
# 6. sort -n - 按数字排序（出现次数）
# 7. tail -1 - 取最后一行（出现次数最多的文件）
# 8. awk '{print $2}' - 取文件名（第 2 列）
gedit `grep $keyword * |cut -d":" -f1 |sort |grep -v ~$ |uniq -c |sort -n |tail -1 |awk '{print $2}'`

# 说明：
# 这个脚本的逻辑是找到包含关键字次数最多的文件并打开
# 可以根据需要修改为列出所有匹配的文件
