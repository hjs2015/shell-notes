#!/bin/bash
# =============================================================================
# 脚本名称：03_file_exist_check.sh
# 功能描述：检查文件是否存在
# 难度等级：⭐⭐ 入门
# 知识点：
#   - read -p 读取用户输入
#   - [ -e 文件 ] - 测试文件是否存在（exist）
#   - if-else 条件判断
#   - echo 输出信息
# 使用方法：
#   chmod +x 03_file_exist_check.sh
#   ./03_file_exist_check.sh
# 文件测试操作符：
#   -e 文件 - 文件是否存在
#   -f 文件 - 是否为普通文件
#   -d 文件 - 是否为目录
#   -r 文件 - 是否可读
#   -w 文件 - 是否可写
#   -x 文件 - 是否可执行
# =============================================================================

# 提示用户输入文件名
read -p "input a file:" file

# 方法一：使用 -e 测试文件是否存在
# 也可以用：ls $file &> /dev/null; if [ $? -eq 0 ]; then ...
if [ -e $file ]; then
	echo "$file exist"
else
	echo "$file not exist"
fi

# 说明：
# 1. [ -e $file ] 是测试命令，等价于 test -e $file
# 2. 如果文件存在，条件为真，执行 then 后面的语句
# 3. 如果文件不存在，条件为假，执行 else 后面的语句
# 4. 注意变量 $file 最好加上引号，防止文件名中有空格：[ -e "$file" ]
