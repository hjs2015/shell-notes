#!/bin/bash
# =============================================================================
# 脚本名称：09_find_dead_links_recursive.sh
# 功能描述：递归查找死链接 - 遍历目录及其子目录
# 难度等级：⭐⭐⭐⭐ 高级
# 知识点：
#   - read -p 读取用户输入
#   - [ ! -d $dir ] 判断是否为目录
#   - 函数定义和递归调用
#   - for i in $1/* 遍历目录内容
#   - [ -L $i ] 判断是否为符号链接
#   - [ ! -e $i ] 判断目标是否存在
#   - 递归函数调用
# 使用方法：
#   chmod +x 09_find_dead_links_recursive.sh
#   ./09_find_dead_links_recursive.sh
# 什么是死链接？
#   符号链接指向的目标文件不存在时，称为死链接
# =============================================================================

# 提示用户输入目录
read -p "输入一个目录:" dir

# 检查是否为目录
if [ ! -d $dir ]; then
	echo "不是目录，重试"
	sh $0  # 重新执行脚本
	exit 1
fi

# 定义递归函数查找死链接
# $1 是函数的第一个参数（目录路径）
finddeadlink() {
	# 遍历目录中的所有内容
	# $1/* 表示参数 1 目录下的所有文件
	for i in $1/*
	do
		# 检查是否为死链接
		# -L 测试是否为符号链接
		# ! -e 测试目标是否不存在
		# -a 表示逻辑与（and）
		if [ -L $i -a ! -e $i ]; then
			# 是死链接，显示出来
			echo "$i是死链接"
		# 检查是否为目录
		elif [ -d $i ]; then
			# 是目录，递归调用自己
			finddeadlink $i
		fi		 
	done
}

# 调用函数查找死链接
finddeadlink $dir

# 说明：
# 1. 递归函数可以遍历所有子目录
# 2. $1/* 匹配目录下的所有文件和子目录
# 3. -L 测试符号链接，-e 测试存在性
# 4. 对于死链接：-L 为真，-e 为假
# 5. 对于目录：递归调用自己

# 递归原理：
# 1. 函数调用自己
# 2. 每次调用处理一个子目录
# 3. 直到没有更多子目录为止
# 4. 这叫做"深度优先搜索"

# 对比：
# 方法 1（非递归）：find $dir -type l ! -exec test -e {} \; -print
# 方法 2（递归）：本脚本的函数递归方式

# 注意：
# 1. 对于非常大的目录树，递归可能比较慢
# 2. 可以用 find 命令替代，性能更好
# 3. 递归深度受系统限制
