#!/bin/bash
# =============================================================================
# 脚本名称：01_char_type_check.sh
# 功能描述：字符类型检查 - 判断输入字符的类型
# 难度等级：⭐⭐ 入门
# 知识点：
#   - read -n 1 读取 1 个字符
#   - case 语句模式匹配
#   - [[:upper:]] [[:lower:]] 字符类
#   - if [[ =~ ]] 正则匹配
#   - elif 多分支判断
# 使用方法：
#   chmod +x 01_char_type_check.sh
#   ./01_char_type_check.sh
# =============================================================================

# 读取用户输入的一个字符
# -n 1 表示只读取 1 个字符（不需要按回车）
# -p 显示提示信息
read -n 1 -p "input a char:" char

# 显示空行（因为 read -n 1 后没有换行）
echo

# ==================== 方法 1：case 语句（注释掉）====================
# case "$char" in
# 	[[:upper:]] )      # 匹配大写字母
# 		echo "大写字母"
# 		;;
# 	[[:lower:]] )      # 匹配小写字母
# 		echo "小写字母"
# 		;;
# 	[0-9] )           # 匹配数字
# 		echo "数字"
# 		;;
# 	* )               # 匹配其他所有字符
# 		echo "其它"
# esac

# ==================== 方法 2：if-elif-else ====================
# [[ $char =~ [A-Z] ]] 使用正则表达式匹配
# =~ 是正则匹配操作符
if [[ $char =~ [A-Z] ]]; then
	echo "大写字母"
elif [[ $char =~ [a-z] ]]; then
	echo "小写字母"
elif [[ $char =~ [0-9] ]]; then
	echo "数字"
else
	echo "其它"
fi

# 说明：
# 1. read -n 1 读取 1 个字符后立即返回，不需要按回车
# 2. [[:upper:]] 是 POSIX 字符类，匹配所有大写字母
# 3. [[:lower:]] 匹配所有小写字母
# 4. [0-9] 匹配数字 0-9
# 5. * 是通配符，匹配所有其他情况
# 6. [[ =~ ]] 是 Bash 的正则匹配语法

